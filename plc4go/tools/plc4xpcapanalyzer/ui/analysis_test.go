func TestMessageNameStripsThePointerAndTheGeneratedPrefix(t *testing.T) {
	pinGlobals(t)
	result := Analyze(t.Context(), writeCBus(t, pcapfixture.CBusSession()), Sink{})
	require.NoError(t, result.Err)

	var named int
	for _, record := range result.Records {
		if record.Summary == "" {
			continue
		}
		named++
		assert.NotContains(t, record.Summary, "*", "%q must not carry the pointer marker", record.Summary)
		assert.NotContains(t, record.Summary, ".", "%q must be the bare type name", record.Summary)
		assert.False(t, strings.HasPrefix(record.Summary, "_"), "%q must not carry the generated-type prefix", record.Summary)
	}
	assert.Positive(t, named, "the fixture parses, so at least one record must be named")
}

func TestDirectionFollowsTheConfiguredClient(t *testing.T) {
	pinGlobals(t)
	result := Analyze(t.Context(), writeCBus(t, pcapfixture.CBusSession()), Sink{})
	require.NoError(t, result.Err)

	var requests, responses int
	for _, record := range result.Records {
		switch record.Direction {
		case DirectionRequest:
			requests++
		case DirectionResponse:
			responses++
		}
	}
	assert.Positive(t, requests, "the fixture interleaves both directions")
	assert.Positive(t, responses)
}

