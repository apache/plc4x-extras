// These tests drive the analysis with real protocol bytes, generated by the same fixture
// builder demo mode uses. Nothing here needs a capture file on disk beforehand, a network, or
// a device.

// recordingReporter records what an analysis told it, so a test can assert the reporter is
// actually driven. It is mutex-guarded because the reporter is called from whichever goroutine
// is doing the work and the race detector runs over this package.
type recordingReporter struct {
	mu           sync.Mutex
	phases       []string
	totals       []int
	advanced     int
	doneCalls    int
	lastProgress progress.Update
}

func (r *recordingReporter) Start(total int, description string) {
	r.mu.Lock()
	defer r.mu.Unlock()
	r.phases = append(r.phases, description)
	r.totals = append(r.totals, total)
}

func (r *recordingReporter) Advance(delta int) {
	r.mu.Lock()
	defer r.mu.Unlock()
	r.advanced += delta
}

func (r *recordingReporter) SetDescription(string) {}

func (r *recordingReporter) Done() {
	r.mu.Lock()
	defer r.mu.Unlock()
	r.doneCalls++
}

func (r *recordingReporter) snapshot() recordingReporter {
	r.mu.Lock()
	defer r.mu.Unlock()
	return recordingReporter{
		phases:       append([]string(nil), r.phases...),
		totals:       append([]int(nil), r.totals...),
		advanced:     r.advanced,
		doneCalls:    r.doneCalls,
		lastProgress: r.lastProgress,
	}
}

// writeCBus writes a C-Bus capture into a temporary directory and returns the request that
// analyses it.
func writeCBus(t *testing.T, packets []pcapfixture.Packet) Request {
	t.Helper()
	path := filepath.Join(t.TempDir(), "cbus.pcap")
	require.NoError(t, pcapfixture.WriteCBus(path, packets))
	return Request{Protocol: protocol.CBus, PcapFile: path, Client: pcapfixture.ClientIP}
}

func TestAnalyzeProducesARecordPerPacket(t *testing.T) {
	pinGlobals(t)
	request := writeCBus(t, pcapfixture.CBusSession())

	result := Analyze(t.Context(), request, Sink{})

	require.NoError(t, result.Err)
	assert.Len(t, result.Records, len(pcapfixture.CBusSession()),
		"every packet in the capture has to reach the table, whatever the codec made of it")
	assert.Equal(t, len(pcapfixture.CBusSession()), result.Counters.Walked)
	for i, record := range result.Records {
		assert.Positive(t, record.Number, "record %d must carry the packet number a user can compare with Wireshark", i)
		assert.Equal(t, protocol.CBus.Name, record.Protocol)
		assert.NotEmpty(t, record.Original, "record %d must keep the captured payload for the detail pane", i)
	}
}

// TestAnalyzeRoundTripsTheCleanSession is the property that makes the fixtures worth having:
// the analyzer's whole job is parse, re-serialize, compare, and a session built from real
// protocol bytes has to come back byte-identical.
func TestAnalyzeRoundTripsTheCleanSession(t *testing.T) {
	pinGlobals(t)
	request := writeCBus(t, pcapfixture.CBusSession())

	result := Analyze(t.Context(), request, Sink{})

	require.NoError(t, result.Err)
	assert.Zero(t, result.Counters.ParseFail)
	assert.Zero(t, result.Counters.SerializeFail)
	assert.Zero(t, result.Counters.CompareFail)
	assert.Zero(t, result.Counters.Issues(), "a clean session must produce no findings")
	for _, record := range result.Records {
		if record.Verdict == VerdictOK {
			assert.Equal(t, -1, record.DiffOffset, "packet %d compared equal, so it has no difference offset", record.Number)
			assert.Equal(t, record.Original, record.Reserialized)
		}
	}
}

// TestAnalyzeReportsTheBrokenPayloads is the other half: the deliberately broken payloads have
// to be counted as findings rather than quietly skipped.
func TestAnalyzeReportsTheBrokenPayloads(t *testing.T) {
	pinGlobals(t)
	clean := Analyze(t.Context(), writeCBus(t, pcapfixture.CBusSession()), Sink{})
	broken := Analyze(t.Context(), writeCBus(t, pcapfixture.CBusSessionWithFailures()), Sink{})

	require.NoError(t, clean.Err)
	require.NoError(t, broken.Err)
	assert.Positive(t, broken.Counters.Issues(),
		"the failure fixture exists so that the findings tab and the failure counters have something in them")
	assert.Greater(t, broken.Counters.Issues(), clean.Counters.Issues())

	var findings []Record
	for _, record := range broken.Records {
		if record.Verdict.IsIssue() {
			findings = append(findings, record)
		}
	}
	require.NotEmpty(t, findings)
	for _, finding := range findings {
		assert.NotEmpty(t, finding.Reason, "a finding with no reason tells the user nothing")
	}
}

