func TestFirstDifference(t *testing.T) {
	for name, testCase := range map[string]struct {
		a, b []byte
		want int
	}{
		"identical":         {[]byte("abc"), []byte("abc"), -1},
		"both empty":        {nil, nil, -1},
		"differs at start":  {[]byte("abc"), []byte("xbc"), 0},
		"differs in middle": {[]byte("abcd"), []byte("abxd"), 2},
		"a is a prefix":     {[]byte("ab"), []byte("abc"), 2},
		"b is a prefix":     {[]byte("abc"), []byte("ab"), 2},
		"one empty":         {[]byte{}, []byte("a"), 0},
	} {
		t.Run(name, func(t *testing.T) {
			assert.Equal(t, testCase.want, FirstDifference(testCase.a, testCase.b))
		})
	}
}

