// TestAnalyzeDrivesEveryPhase pins the breadcrumb the run panel draws. Deleting a phase would
// leave the panel showing a stage the run never reaches.
func TestAnalyzeDrivesEveryPhase(t *testing.T) {
	pinGlobals(t)
	request := writeCBus(t, pcapfixture.CBusSession())
	reporter := &recordingReporter{}

	result := Analyze(t.Context(), request, Sink{Progress: reporter})
	require.NoError(t, result.Err)

	recorded := reporter.snapshot()
	assert.Equal(t, Phases, recorded.phases, "the run panel's breadcrumb is these phases, in this order")
	assert.Positive(t, recorded.advanced, "a bar that never advances is a bar that says nothing")
	assert.Positive(t, recorded.doneCalls, "the reporter must be finished, not abandoned")
	require.Len(t, recorded.totals, len(Phases))
	assert.Equal(t, len(pcapfixture.CBusSession()), recorded.totals[len(recorded.totals)-1],
		"the analyze phase must announce how many packets it is about to walk")
}

// TestAnalyzeObservesEveryRecord pins the streaming that fills the table while a run is in
// flight. Without it the table would stay empty until the very end of a long capture.
func TestAnalyzeObservesEveryRecord(t *testing.T) {
	pinGlobals(t)
	request := writeCBus(t, pcapfixture.CBusSession())

	var mu sync.Mutex
	var observed []Record
	result := Analyze(t.Context(), request, Sink{Observe: func(record Record) {
		mu.Lock()
		defer mu.Unlock()
		observed = append(observed, record)
	}})

	require.NoError(t, result.Err)
	mu.Lock()
	defer mu.Unlock()
	assert.Equal(t, result.Records, observed, "what was streamed must be exactly what was returned, in order")
}

// TestAnalyzeStopsWhenTheContextIsCancelled is what makes the esc-abort binding real.
func TestAnalyzeStopsWhenTheContextIsCancelled(t *testing.T) {
	pinGlobals(t)
	request := writeCBus(t, pcapfixture.CBusSessionWithFailures())

	ctx, cancel := context.WithCancel(t.Context())
	cancel()
	result := Analyze(ctx, request, Sink{})

	assert.True(t, result.Aborted, "a cancelled run must say it was cancelled rather than look complete")
	assert.NoError(t, result.Err, "an abort is not a failure")
}

