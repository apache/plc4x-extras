func TestAnalyzeMeasuresElapsedWithTheInjectedClock(t *testing.T) {
	pinGlobals(t)
	request := writeCBus(t, pcapfixture.CBusSession())

	var calls int
	result := Analyze(t.Context(), request, Sink{Clock: func() time.Time {
		calls++
		return time.Unix(0, 0).Add(time.Duration(calls) * time.Second)
	}})

	require.NoError(t, result.Err)
	assert.Equal(t, time.Second, result.Elapsed, "elapsed must come from the injected clock, not the wall clock")
}

